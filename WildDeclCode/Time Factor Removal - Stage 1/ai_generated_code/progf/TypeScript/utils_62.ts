/** Useful to fix already-saved bad URLs (missing /public, spaces). */
function normalizeSupabasePublicUrl(u: string): string {
  const fixed = u.includes("/storage/v1/object/public/")
    ? u
    : u.replace("/storage/v1/object/", "/storage/v1/object/public/");
  return encodeURI(fixed);
}

function serializeBigInt(value: unknown): any {
  if (typeof value === "bigint") {
    return value.toString();
  }
  if (Array.isArray(value)) {
    return value.map(serializeBigInt);
  }
  if (value && typeof value === "object") {
    const result: Record<string, any> = {};
    for (const [k, v] of Object.entries(value)) {
      result[k] = serializeBigInt(v);
    }
    return result;
  }
  return value;
}
function timeUntil(raw: Dateish) {
  if (raw == null || raw === '') return '--'; 
  let d: Date;

  switch (typeof raw) {
    case 'string': {
      const s = String(raw).trim();
            if (/^\d+$/.test(s)) {
        // purely digits → epoch seconds/ms encoded as string
        const n = Number(s);
        d = new Date(n < 1e12 ? n * 1000 : n);   // sec ↔ ms heuristic
      } else {
        // ISO-8601 or RFC-2822
        d = new Date(s.replace(' ', 'T'));       // tolerant of “2025-07-31 17:50Z”
      }
      break;
    }
    case 'number':
    case 'bigint': {
      const n = Number(raw);
      d = new Date(n < 1e12 ? n * 1000 : n);
      break;
    }
    case 'object':
      if (raw instanceof Date) d = raw; else return '--';
      break;
    default:
      return '--';
  }

  return isNaN(d.getTime()) ? '--' : formatDistanceToNowStrict(d);
}
