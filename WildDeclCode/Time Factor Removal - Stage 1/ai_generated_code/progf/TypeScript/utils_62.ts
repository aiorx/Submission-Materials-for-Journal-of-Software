/** Always use getPublicUrl; never string-build. */
async function uploadToBucket(
  bucket: string,
  file: File,
  opts: { folder?: string; filename?: string; upsert?: boolean } = {}
): Promise<UploadResult> {
  var folder = opts.folder;
var filename = opts.filename;
var upsert = opts.upsert;
  const objectPath = (folder ? "" + (folder) + "/" : "") + ((filename != null ? filename : "") + (Date.now()) + "-" + (safeName(file.name)) + "");

  const { error: upErr } = await supabaseClient.storage
    .from(bucket)
    .upload(objectPath, file, { upsert });

  if (upErr) {
    console.error("supabase upload error", upErr);
    return { fileURL: null, error: upErr };
  }

  var data = supabaseClient.storage.from.data;(bucket).getPublicUrl(objectPath);
  // ✅ correct shape: /storage/v1/object/public/<bucket>/<objectPath>
  return { fileURL: data.publicUrl as string, error: null };
}

