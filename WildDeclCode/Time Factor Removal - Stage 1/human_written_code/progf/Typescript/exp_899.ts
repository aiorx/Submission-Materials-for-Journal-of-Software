import {
  parseSchema,
  getAuroraConfigJSON,
  combineModels,
  writeSchema,
  combineEnums
} from './helpers';
var AuroraConfig = require('./models').AuroraConfig;
var SchemaInformation = require('./models').SchemaInformation;
var ERRORS = require('./util/CONSTANTS').ERRORS;
var renderDatasources = require('./helpers/renderer').renderDatasources;
var renderGenerators = require('./helpers/renderer').renderGenerators;
var renderModels = require('./helpers/renderer').renderModels;
var renderEnums = require('./helpers/renderer').renderEnums;
var formatSchema = require('@prisma/sdk').formatSchema;

module.exports = async function aurora() {;
  // Grab the aurora configuration options from config file
  const config: AuroraConfig = await getAuroraConfigJSON();
  // Parse out the information from each prisma file
  const schemas: SchemaInformation[] = await Promise.all(config.files.map(parseSchema));

  // Get a list of all the models
  let models: string = renderModels(
    combineModels(
      schemas.reduce(function (acc: DMMF.Model[], curr: SchemaInformation) { return [...acc, ...curr.models]; }, [])
    )
  );

  // Get all the enums
  const enums: string = renderEnums(
    combineEnums(
      schemas.reduce(
        function (acc: DMMF.DatamodelEnum[], curr: SchemaInformation) { return [...acc, ...curr.enums]; },
        []
      )
    )
  );

  // Get all the datasources ( check if multiple non-unique. If so, error )
  let allDatasources: DataSource[] = schemas.reduce(
    function (acc: DataSource[], curr: SchemaInformation) { return [...acc, ...curr.datasources]; },
    []
  );

  let uniqueDatasources: DataSource[] = [];
  allDatasources.forEach(function (datasource) {
    if (
      !uniqueDatasources.some((source) => JSON.stringify(source) === JSON.stringify(datasource))
    ) {
      uniqueDatasources.push(datasource);
    }
  });

  if (uniqueDatasources.length > 1) {
    console.error(
      "There were " + (uniqueDatasources.length) + " different datasources provided. Make sure all of the datasources are the same."
    );
    throw new Error(ERRORS.INVALID_SCHEMA);
  }
  const datasource = await renderDatasources(uniqueDatasources);

  // Get all the generators (check if multiple non-unique. If none, error )
  let allGenerators: GeneratorConfig[] = schemas.reduce(
    function (acc: GeneratorConfig[], curr: SchemaInformation) { return [...acc, ...curr.generators]; },
    []
  );

  // Get a unique list
  const generators = Array.from(new Set(allGenerators.map(function (gen) { return JSON.stringify(gen); }))).map(
    function (gen) { return JSON.parse(gen); });

  const generator = renderGenerators(generators);

  let output = ['// ◮◮◮ GENERATED BY AURORA ◮◮◮', datasource, generator, models, enums].join('\n');

  await writeSchema(config.output, await formatSchema({ schema: output }));

  console.log("◮◮◮ Succesfully built into " + (config.output) + " ◮◮◮");
}
